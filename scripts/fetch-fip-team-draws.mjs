#!/usr/bin/env node
// Fetch a FIP national-team championship from the matchscorerlive TEAM widget and
// write it in the same shape as the archived draws this repo already ships, so
// `build-national-teams.mjs` can read it without knowing where it came from.
//
//   node scripts/fetch-fip-team-draws.mjs FIP-2025-127 [FIP-2025-123 ...]
//   node scripts/fetch-fip-team-draws.mjs --all          (everything in EVENTS)
//
// WHY THIS EXISTS. The national-teams section could only see three editions,
// because the only widget path the FIP adapter knows — `/screen/oopbyday/<id>/<day>`
// — 404s once a tournament is finished. That was recorded as "re-fetching an old FIP
// draw is not an option" and it is wrong twice over:
//
//   * a padelfip event page carries its widget id as `FIP-<year>-<n>` inside the
//     iframe src, NOT as the `idEvent_<digits>` class the tour adapter greps for
//     (championship pages have a literal `idEvent_#1001` placeholder there), and
//   * `/screen/teamresults/<id>/<day>` and `/screen/groups/<id>` DO still serve
//     finished tournaments, and teamresults is richer than oopbyday: it states the
//     TIE score and the round label, not just the rubbers.
//
// So a national-team championship is re-fetchable years later. Verified 2026-09-26
// against the 2025 Euro Padel Cup, whose event page had been the standing example of
// an unsourceable edition.
//
// WHAT IT WRITES. `public/data/national-teams/draws/<key>.json`, NOT
// `public/data/archive/t/` — that directory is generated by padel-db's
// export_archive.py from padel.db, and a file this script owns must not sit in a
// directory another job rewrites.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(ROOT, "public", "data", "national-teams", "draws");

const HEADERS = {
  Referer: "https://www.padelfip.com/",
  "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124 Safari/537.36",
};
const WIDGET = "https://widget.matchscorerlive.com/screen";

// The national-TEAM events on padelfip's championships calendar 2023-2026 that carry
// a team widget. `key` is what the rest of the pipeline calls the edition; `wp` is
// the padelfip event slug it came from, kept so a human can check the source.
export const EVENTS = [
  { id: "FIP-2025-123", key: "fip-2025-euro-cup-ph12", wp: "fip-euro-padel-cup-phase-1-2" },
  { id: "FIP-2025-127", key: "fip-2025-euro-cup-final8", wp: "fip-euro-padel-cup-2025-final-8" },
  { id: "FIP-2025-126", key: "fip-2025-junior-world-cup", wp: "fip-junior-world-cup-by-teams-2025" },
  { id: "FIP-2025-128", key: "fip-2025-asia-cup", wp: "fip-asia-padel-cup-2025" },
  { id: "FIP-2026-3111", key: "fip-2026-wc-q-noram", wp: "fip-world-cup-2026-qualifiers-north-central-america" },
  { id: "FIP-2026-3416", key: "fip-2026-wc-q-souam", wp: "fip-world-cup-2026-qualifiers-south-america" },
  { id: "FIP-2026-3918", key: "fip-2026-wc-q-europe", wp: "fip-world-cup-2026-qualifiers-europe-2026" },
  { id: "FIP-2026-3803", key: "fip-2026-senior-world-cup", wp: "fip-senior-world-cup-2026-2026" },
];

const MAX_DAYS = 14;

const dec = (s) =>
  s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(+d))
    .replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#039;|&apos;/g, "'")
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&nbsp;/g, " ");
const text = (h) => dec(h.replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();

async function get(url) {
  const r = await fetch(url, { headers: HEADERS, signal: AbortSignal.timeout(30000) });
  if (!r.ok) return null;
  return await r.text();
}

/** Split on a tag with the given class, keeping each block whole. */
function blocks(html, marker) {
  const out = [];
  let i = html.indexOf(marker);
  while (i !== -1) {
    const next = html.indexOf(marker, i + marker.length);
    out.push(html.slice(i, next === -1 ? html.length : next));
    i = next;
  }
  return out;
}

/**
 * One day's ties. A tie card carries `data-draw` (the widget's own id for MENS /
 * WOMENS, resolved from the draw selector) and `data-view` F/L/U — only F is taken,
 * because an upcoming card has empty rubbers and a live one has a moving score.
 */
function parseDay(html, genderOf) {
  const out = [];
  for (const card of blocks(html, '<div class="col-12 col-lg-6 col-xl-4 mb-3"')) {
    const draw = (card.match(/data-draw="(\d+)"/) || [])[1];
    const view = (card.match(/data-view="([FLU])"/) || [])[1];
    if (view !== "F") continue;
    const gender = genderOf[draw];
    if (!gender) continue;

    const head = card.match(/<div class="text-uppercase text-lg bold">([\s\S]*?)<\/div>\s*<div class="text-uppercase text-lg">([\s\S]*?)<\/div>/);
    const group = head ? text(head[1]) : "";
    const phase = head ? text(head[2]) : "";
    const nations = [...card.matchAll(/\/images\/flags\/([A-Z]{3})\.jpg/g)].map((m) => m[1]);
    const names = [...card.matchAll(/<span class="tie-team-name">([\s\S]*?)<\/span>/g)].map((m) => text(m[1]));
    if (nations.length < 2) continue;

    // The rubbers table repeats a court row and then one row per rubber.
    let court = "";
    const rubbers = [];
    for (const row of card.split("<tr").slice(1)) {
      const c = row.match(/<td colspan="5"[\s\S]*?<div class="bold text-center">([\s\S]*?)<\/div>/);
      if (c) { court = text(c[1]); continue; }
      const sides = [...row.matchAll(/<div class="tie-team([^"]*)">([\s\S]*?)<small[^>]*>([A-Z]{3})<\/small>/g)];
      if (sides.length !== 2) continue;
      // Each score column holds the two sides' games as two divs, top side first.
      const cols = [...row.matchAll(/<td class="text-center">\s*<div class="text-lg[^"]*">([\s\S]*?)<\/div>\s*<div class="text-lg[^"]*">([\s\S]*?)<\/div>\s*<\/td>/g)];
      const sets = cols
        .map((m) => [text(m[1]), text(m[2])])
        .filter(([a, b]) => a !== "" && b !== "");
      // The widget bolds the winning side and mutes the loser. Prefer that over
      // counting sets: it is the widget's own verdict and it survives a retirement.
      const boldTop = /\bbold\b/.test(sides[0][1] ? sides[0][1] : "") || /\bbold\b/.test(sides[0][1]);
      const winner = /\bbold\b/.test(sides[0][1]) ? 0 : /\bbold\b/.test(sides[1][1]) ? 1 : null;
      rubbers.push({
        court,
        teams: sides.map(([, , names_, cc], i) => 0) && sides.map((s) => ({
          name: text(s[2]),
          country: s[3],
          players: text(s[2]).split("/").map((n) => ({ name: n.trim(), country: s[3] })),
        })),
        sets,
        winner,
        _boldTop: boldTop,
      });
    }
    out.push({ gender, group, phase, nations: nations.slice(0, 2), names: names.slice(0, 2), rubbers });
  }
  return out;
}

/**
 * The card header is two halves: a block ("Group A", "Position 1-4") and a phase
 * ("RR", "Group stage", "Semifinals", "Final"). The SAME group phase is labelled
 * "RR" on one day and "Group stage" on another inside one event, so the phase is
 * dropped for group ties and kept for everything else — where it is the part that
 * says which position was at stake.
 */
const roundLabel = (group, phase) =>
  /^(RR|Group stage|Round Robin)$/i.test(phase) ? group || "Group stage" : [group, phase].filter(Boolean).join(" ").trim();

/** The draw selector maps the widget's numeric draw ids to MENS / WOMENS. */
function genderMap(html) {
  const sel = html.match(/<select class="custom-select" id="draw-selector">([\s\S]*?)<\/select>/);
  const map = {};
  if (!sel) return map;
  for (const m of sel[1].matchAll(/<option value="(\d+)">([\s\S]*?)<\/option>/g)) {
    // Labels are not one vocabulary: MENS/WOMENS at a senior event, BOYS/GIRLS at a
    // junior one — and the 2025 junior world cup ships "GILRS EUROPEAN Q", so the
    // typo has to match too or half that event disappears silently.
    const label = text(m[2]).toUpperCase();
    if (/WOM|LADIES|GIRL|GILRS/.test(label)) map[m[1]] = "women";
    else if (/MEN|MAN|BOY/.test(label)) map[m[1]] = "men";
  }
  return map;
}

const MONTH = { JAN: 1, FEB: 2, MAR: 3, APR: 4, MAY: 5, JUN: 6, JUL: 7, AUG: 8, SEP: 9, OCT: 10, NOV: 11, DEC: 12 };

/**
 * The day strip is the only honest source for WHEN this was played. padelfip's own
 * event page can disagree with it — the 2025 Euro Cup Final 8 page still carries a
 * July order-of-play link for a tournament the widget dates to late October — so the
 * dates come from the days that actually hold ties, never from the event page.
 */
function dayDates(html, year) {
  const out = {};
  for (const m of html.matchAll(/href="\/screen\/teamresults\/[^/]+\/(\d+)[^"]*"[\s\S]{0,200}?class="play-day-date">([A-Z]{3}) (\d{1,2})</g)) {
    const mo = MONTH[m[2]];
    if (mo) out[+m[1]] = `${year}-${String(mo).padStart(2, "0")}-${String(+m[3]).padStart(2, "0")}`;
  }
  return out;
}

/** The event's own title, from padelfip's REST API by slug. */
async function eventTitle(slug) {
  try {
    const r = await fetch(`https://www.padelfip.com/wp-json/wp/v2/events?slug=${slug}`, { headers: HEADERS, signal: AbortSignal.timeout(20000) });
    const j = await r.json();
    return dec(j?.[0]?.title?.rendered || "").replace(/\s+/g, " ").trim();
  } catch { return ""; }
}

async function fetchEvent(ev) {
  const first = await get(`${WIDGET}/teamresults/${ev.id}/1?t=tol`);
  if (!first) return { ...ev, error: "day 1 did not serve" };
  const genderOf = genderMap(first);
  const year = +(ev.id.match(/FIP-(\d{4})-/) || [])[1];
  const dates = dayDates(first, year);
  const title = await eventTitle(ev.wp);
  const days = [...new Set([...first.matchAll(new RegExp(`/screen/teamresults/${ev.id}/(\\d+)`, "g"))].map((m) => +m[1]))];
  const lastDay = Math.min(days.length ? Math.max(...days) : 1, MAX_DAYS);

  const matches = [], ties = [];
  for (let day = 1; day <= lastDay; day++) {
    const html = day === 1 ? first : await get(`${WIDGET}/teamresults/${ev.id}/${day}?t=tol`);
    if (!html) continue;
    for (const t of parseDay(html, genderOf)) {
      const [a, b] = t.nations;
      ties.push({ day, gender: t.gender, group: t.group, phase: t.phase, a, b, n: t.rubbers.length });
      for (const r of t.rubbers) {
        // Keep the archive's own match shape: className/round/court/teams/score.
        // A tie that is already decided leaves its remaining rubbers on court but
        // unplayed: the widget prints the pairs with no score and bolds nobody.
        // That is a fixture, not a match, so it must not ship as one.
        const played = r.winner !== null || r.sets.length > 0;
        matches.push({
          className: t.gender === "women" ? "Women" : "Men",
          round: roundLabel(t.group, t.phase),
          court: r.court,
          status: played ? "final" : "notplayed",
          day,
          teams: r.teams.map((s) => ({ name: s.name, players: s.players })),
          score: { sets: r.sets, winner: r.winner },
        });
      }
    }
  }
  const played = [...new Set(matches.filter((m) => m.status === "final").map((m) => dates[m.day]).filter(Boolean))].sort();
  return { ...ev, lastDay, matches, ties, genders: genderOf, title, year, start: played[0] || "", end: played[played.length - 1] || "" };
}


// ------------------------------------------------------------------- discovery
// The reason a new championship does not appear here on its own: EVENTS above is
// hand-written, because the label cannot be read off the title. "FIP SENIOR WORLD
// CUP" is the VETERANS event, not the senior national team, and publishing it as
// the latter would put a veterans result in a nation's national-team record. So
// discovery REPORTS what it finds and never adds it.
//
//   node scripts/fetch-fip-team-draws.mjs --discover [year ...]
//
// It walks padelfip's championships calendar, pulls each event's widget id out of
// the iframe src (the `idEvent_` class is a `#1001` placeholder on these pages) and
// says which ones carry a TEAM widget and are not already known.
// Editions already published from an ARCHIVED draw, under the archive's own key.
// Discovery would otherwise flag them as new every single week — an alert that
// never clears is an alert nobody reads.
const KNOWN_ELSEWHERE = {
  "FIP-2026-2811": "fip-296741 (Junior Euro Padel Cup 2026, from the archive)",
  "FIP-2024-4403": "fip-135412 (World Championships 2024, from the archive)",
};

async function discover(years) {
  const known = new Set(EVENTS.map((e) => e.id));
  const found = [];
  for (const y of years) {
    const cal = await get(`https://www.padelfip.com/calendar-fip-championships/?events-year=${y}`);
    if (!cal) { console.log(`${y}: calendar did not serve`); continue; }
    const slugs = [...new Set([...cal.matchAll(/https:\/\/www\.padelfip\.com\/events\/([a-z0-9-]+)\//g)].map((m) => m[1]))];
    for (const slug of slugs) {
      const html = await get(`https://www.padelfip.com/events/${slug}/`);
      if (!html) continue;
      const frames = [...new Set([...html.matchAll(/widget\.matchscorerlive\.com\/screen\/([a-z]+)\/(FIP-\d{4}-\d+)/g)].map((m) => `${m[1]}|${m[2]}`))];
      const team = frames.filter((f) => f.startsWith("teamresults|") || f.startsWith("groups|"));
      if (!team.length) continue;
      const id = team[0].split("|")[1];
      found.push({ y, slug, id, known: known.has(id) || !!KNOWN_ELSEWHERE[id], screens: [...new Set(frames.map((f) => f.split("|")[0]))].join("+") });
    }
  }
  const fresh = found.filter((f) => !f.known);
  console.log(`discover: ${found.length} team events across ${years.join(", ")}, ${fresh.length} not in EVENTS`);
  for (const f of found.filter((x) => KNOWN_ELSEWHERE[x.id])) console.log(`  (${f.id} already published as ${KNOWN_ELSEWHERE[f.id]})`);
  for (const f of fresh) {
    console.log(`  NEW ${f.id}  ${f.slug}  (${f.screens})`);
    console.log(`      https://www.padelfip.com/events/${f.slug}/`);
  }
  if (fresh.length) {
    console.log("  -> add to EVENTS here and to TEAM_DRAWS in build-national-teams.mjs WITH A LABEL");
    console.log("     CHECKED AGAINST THE SQUADS: FIP calls its veterans events \"Senior\".");
  }
  return fresh;
}

const args = process.argv.slice(2);
if (args.includes("--discover")) {
  const now = new Date().getFullYear();
  const years = args.filter((a) => /^\d{4}$/.test(a)).map(Number);
  const fresh = await discover(years.length ? years : [now, now + 1]);
  process.exit(fresh.length ? 3 : 0); // 3 = something new to label, by hand
}

const wanted = args.includes("--all") ? EVENTS : EVENTS.filter((e) => args.includes(e.id) || args.includes(e.key));
if (!wanted.length) {
  console.error("usage: fetch-fip-team-draws.mjs <FIP-YYYY-N | key | --all | --discover [year ...]>");
  process.exit(2);
}

fs.mkdirSync(OUT_DIR, { recursive: true });
for (const ev of wanted) {
  const r = await fetchEvent(ev);
  if (r.error) { console.log(`${ev.id} ${ev.key}: ${r.error}`); continue; }
  const undecided = r.matches.filter((m) => m.score.winner === null).length;
  const file = path.join(OUT_DIR, `${ev.key}.json`);
  const body = JSON.stringify({
    key: ev.key,
    name: r.title,
    year: r.year,
    start: r.start,
    end: r.end,
    widgetId: ev.id,
    source: `matchscorerlive teamresults ${ev.id}, days 1-${r.lastDay}`,
    sourceUrl: `https://www.padelfip.com/events/${ev.wp}/`,
    fetched: new Date().toISOString().slice(0, 10),
    matches: r.matches,
  }, null, 1) + "\n";
  // Rewriting a file whose only difference is today's date turns a weekly refresh
  // into a weekly commit and a weekly deploy that carry nothing. Compare with the
  // stamp masked out, so `fetched` means "when this draw last changed" rather than
  // "when we last looked" - which is the more useful of the two anyway.
  // Two masks, not one. git checks these files out as CRLF (core.autocrlf) while
  // the generator writes LF, so a byte comparison says "changed" on every single
  // run and the weekly job would commit eight untouched files every Monday.
  const mask = (s) => s.replace(/\r\n/g, "\n").replace(/"fetched": "[^"]*"/, '"fetched": "*"');
  const prev = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  const same = prev !== null && mask(prev) === mask(body);
  if (!same) fs.writeFileSync(file, body);
  const rounds = [...new Set(r.matches.map((m) => m.round))];
  console.log(`${ev.id} ${ev.key}: ${same ? "unchanged, " : ""}${r.ties.length} ties, ${r.matches.length} matches, days 1-${r.lastDay}` +
    `${undecided ? `, ${undecided} with no winner marked` : ""}`);
  console.log(`   genders: ${[...new Set(Object.values(r.genders))].join("/") || "NONE"} | rounds: ${rounds.join(" | ")}`);
}
